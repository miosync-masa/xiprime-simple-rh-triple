"""Fix one rational candidate P = sum a_i p_i (a_i = rounded optimal solution), evaluate the bound exactly,
and emit a Lean data file.  Usage: python3 -I gdll_candidate.py <data dir> <d> <digits> <out.lean> <gate num> <gate den>"""
import sys, json, site
sys.path.append(site.getusersitepackages()); sys.path.insert(0, __import__("os").path.dirname(__import__("os").path.abspath(__file__)))
from fractions import Fraction
from flint import fmpq
import gdll_exact as G
datadir,d,digits,out,gn,gd=sys.argv[1],int(sys.argv[2]),int(sys.argv[3]),sys.argv[4],int(sys.argv[5]),int(sys.argv[6])
J=json.load(open(f"gdll_exact_d{d}.json")); xs=[Fraction(s) for s in J["x"]]
m=max(abs(v) for v in xs); a=[round(v/m*10**digits) for v in xs]          # integers, scale-free
P=G.load(datadir,d)
Pc=sum((G.C(fmpq(ai))*p for ai,p in zip(a,P)),G.C(0))
I0=G.sqint(Pc); I2=G.sqint(Pc*Pc); J3=G.tripleint(Pc,Pc); J4=G.quadint(Pc,Pc)
val=2+(I2+6*J3-12*J4)/(I0*I0); F=lambda v:Fraction(int(v.p),int(v.q))
print("a =",a); print("exact value of the candidate: %.12f"%float(F(val)),"  optimum %.12f"%float(Fraction(J["c"])))
print("gate %d/%d passed (exact rational comparison):"%(gn,gd), F(val)<=Fraction(gn,gd))
deg=Pc.total_degree()
tab=[[Fraction(0)]*(deg+1-i) for i in range(deg+1)]
for (ex,c) in zip(Pc.monoms(),Pc.coeffs()): tab[ex[0]][ex[1]]=F(c)
# clear denominators (scale-free)
from math import lcm
L=1
for row in tab:
    for c in row: L=lcm(L,c.denominator)
tabi=[[int(c*L) for c in row] for row in tab]
def strip(row):
    while row and row[-1]==0: row=row[:-1]
    return row
rows=",\n   ".join("["+", ".join(str(c) for c in strip(r))+"]" for r in tabi)
name=f"P{d}"
open(out,"w").write(f"""import TripleCorrelation.CheckerInt

/-! Candidate for GdLL (arXiv:2303.01095v2) Section 5, data file polynomials-{d}.txt (first block).
P = sum a_i p_i with integer a = {a}, denominators cleared (the bound is scale-free).
Row i lists the coefficients of x^i y^j, j = 0,1,...  Generated by gdll_candidate.py; exact value
computed outside Lean with python-flint: {float(F(val)):.12f}. -/
namespace XiPrime8845.Triple

def {name}i : List (List Int) :=
  [{rows}]

def {name} : List (List ℚ) := {name}i.map (fun r => r.map (fun (c : Int) => (c : ℚ)))

end XiPrime8845.Triple
""")
json.dump({"d":d,"a":a,"value":str(F(val)),"I0":str(F(I0)),"I2":str(F(I2)),"J3":str(F(J3)),"J4":str(F(J4))},open(f"gdll_candidate_d{d}.json","w"))
